/** SVG path data for the map, projected equirectangular into a `w` x `w/2` box. */
export function worldMapPath(w: number): string {
  const h = w / 2;
  return LAND.map(
    (poly) =>
      poly
        .map(([lon, lat], i) => {
          const x = ((lon + 180) / 360) * w;
          const y = ((90 - lat) / 180) * h;
          return `${i ? "L" : "M"}${x.toFixed(1)} ${y.toFixed(1)}`;
        })
        .join("") + "Z",
  ).join("");
}
